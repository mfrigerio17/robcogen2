%% A structure with the Fancy robot model in the format described
%% in "A beginner's guide to 6-D vectors (part 2)" by Roy Featherstone.
%%
%% roy = RoyModel(mgc, mgp, mic, mip)
%%
%% roy is the data struct with the robot model data conforming to
%% Roy's model.
%%
%% mgc is a struct with all the geometric
%% constant properties of the robot model.
%% mic is the same for inertial constant properties.
%%
%% mgp and mip
%% are structs with values for the parametric model properties. Not required if
%% the original robot model is not parametric. The first struct is for geometry
%% parameters, the second for inertial ones.
%%
%% This file has been automatically generated by RobCoGen.

function roy = RoyModel(mgc, mgp, mic, mip)

roy.robotname = 'Fancy';

roy.NB = 5;
roy.parent = zeros(1, 5);

roy.parent(1) = 0;
roy.parent(2) = 1;
roy.parent(3) = 2;
roy.parent(4) = 3;
roy.parent(5) = 4;

roy.jtype{1} = 'Rz';
roy.jtype{2} = 'Pz';
roy.jtype{3} = 'Rz';
roy.jtype{4} = 'Pz';
roy.jtype{5} = 'Rz';

roy.Xtree{1} = eye(6,6);
roy.Xtree{2} = rotx(-0.5*pi) * xlt([mgp.ll,0.0,0.0]);
roy.Xtree{3} = xlt([0.0,0.0,mgc.jC_tz]);
roy.Xtree{4} = rotx(0.5*pi) * xlt([mgc.jD_tx,0.0,0.0]);
roy.Xtree{5} = xlt([0.0,0.0,mgc.jE_tz]);

I = rcg2.RigidBodyInertia.makeTensor3D(mic.link1_ixx,mic.link1_iyy,mic.link1_izz,0.0,0.0,0.0);
roy.I{1} = rcg2.RigidBodyInertia.makeTensor6D(mip.m1, [mic.link1_comx; 0.0; 0.0], I);
I = rcg2.RigidBodyInertia.makeTensor3D(mic.link2_ixx,mic.link2_iyy,mic.link2_izz,0.0,0.0,0.0);
roy.I{2} = rcg2.RigidBodyInertia.makeTensor6D(mic.link2_mass, [0.0; 0.0; mic.link2_comz], I);
I = rcg2.RigidBodyInertia.makeTensor3D(mic.link3_ixx,mic.link3_iyy,mic.link3_izz,0.0,0.0,0.0);
roy.I{3} = rcg2.RigidBodyInertia.makeTensor6D(mic.link3_mass, [mic.link3_comx; 0.0; 0.0], I);
I = rcg2.RigidBodyInertia.makeTensor3D(mic.link4_ixx,mic.link4_iyy,mic.link4_izz,0.0,0.0,0.0);
roy.I{4} = rcg2.RigidBodyInertia.makeTensor6D(mic.link4_mass, [0.0; 0.0; mic.link4_comz], I);
I = rcg2.RigidBodyInertia.makeTensor3D(mic.link5_ixx,mic.link5_iyy,mic.link5_izz,0.0,0.0,0.0);
roy.I{5} = rcg2.RigidBodyInertia.makeTensor6D(mic.link5_mass, [mic.link5_comx; 0.0; 0.0], I);
